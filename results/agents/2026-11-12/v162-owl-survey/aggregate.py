import csv, json, collections
D="/mnt/data1/leechuck/km-work/v161/survey/"
TSV="/mnt/data1/leechuck/km-work/wt/v1.6.1/results/agents/2026-11-10/v160-p3-rerun/data/p3-results.tsv"
meta={r['input']:r for r in csv.DictReader(open(TSV),delimiter="\t")}
rows=[json.loads(l) for l in open(D+"per_input.jsonl")]
IGN={"Prefix","Ontology","Declaration","Class","ObjectProperty","DataProperty","NamedIndividual","AnnotationProperty","Datatype",
"Annotation","AnnotationAssertion","SubAnnotationPropertyOf","AnnotationPropertyDomain","AnnotationPropertyRange"}
F1={"SubClassOf","EquivalentClasses","ObjectIntersectionOf","ObjectSomeValuesFrom","ObjectPropertyDomain","DisjointClasses"}
F2=F1|{"SubObjectPropertyOf","ObjectPropertyChain","TransitiveObjectProperty"}
F3=F1|{"ObjectUnionOf","ObjectComplementOf","ObjectAllValuesFrom","ObjectPropertyRange"}
HI={"SubObjectPropertyOf","EquivalentObjectProperties","InverseObjectProperties","ObjectInverseOf","SymmetricObjectProperty"}
F4=F3|HI
F5=F4|{"ClassAssertion","ObjectPropertyAssertion","ObjectOneOf","ObjectHasValue"}
F4t=F4|{"TransitiveObjectProperty","ObjectPropertyChain"}
F3d=F3|{"DisjointUnion"}
FR=[("F1 EL",F1),("F2 EL+RBox(atomic sub, trans, chains)",F2),("F3 ALC",F3),("F4 ALC+H+I",F4),("F5 F4+ABox+nominals",F5),
    ("x1 F4 + trans + chains (ALCHI+R)",F4t),("x2 F3 + DisjointUnion",F3d)]
def used(r): return {h for h,c in r['heads'].items() if h not in IGN and c>0}
def topuse(r):  # owl:topObjectProperty / bottom roles are outside all fragments
    k=r['kw']; return k.get('topObjectProperty',0)+k.get('bottomObjectProperty',0)>0
def inside(r,F): return not r['input'].endswith('.ttl') and used(r)<=F and not topuse(r) and r['kw'].get('header_import',0)==0
for r in rows:
    m=meta[r['input']]; r['p2']=m['p2_status']; r['route']=m['unforced_route']
out=[]; w=out.append
n=len(rows)
w("# KM v1.6.2 frontend-fragment survey\n")
w(f"Inputs: {n} (checkers-on suite, p3-results.tsv). Generated by survey.py and aggregate.py in this directory; per-input data in per_input.jsonl and per_input.tsv.\n")
# 1 formats
w("## 1. Input formats\n")
w("1780 inputs are OWL 2 Functional-Style Syntax text (extensions .owl 1094 and .ofn 686; none is OWL/XML or RDF/XML, checked by header sniffing of the 1,595 reachable originals and by the head-token counts for all). The remaining 1 input is a Turtle file (`fixtures/utf8_non_ascii.ttl`, a non-ASCII test fixture) that matches no fragment and is excluded from every fragment count. 12 OFN inputs have no `Ontology(<iri>` header IRI and 11 have no Prefix declarations. The v1.6.0 run used `engine/tests/...` paths from a removed worktree (186 files); the survey reads the identical paths in the v1.6.1 worktree.\n")
import os
ext=collections.Counter(os.path.splitext(r['input'])[1] for r in rows)
w("| extension | inputs |\n|---|---|"); [w(f"| {k} | {v} |") for k,v in ext.most_common()]
w(f"\nTotal bytes: {sum(r['size'] for r in rows)/1e9:.2f} GB; largest {max(r['size'] for r in rows)/1e6:.0f} MB; files over 100 MB: {sum(r['size']>1e8 for r in rows)}.\n")
# fragment coverage
groups=[("(a) all",rows),("(b) p2-accepted",[r for r in rows if r['p2']=='accepted'])]
w("## 2. Fragment coverage (inputs entirely inside the fragment; annotations and declarations ignored)\n")
w("Inside means: every axiom/expression head used is in the fragment's allowed set; no Import; no use of owl:topObjectProperty or owl:bottomObjectProperty. Allowed sets:\n")
w("- F1: SubClassOf, EquivalentClasses, DisjointClasses, ObjectIntersectionOf, ObjectSomeValuesFrom, ObjectPropertyDomain (owl:Thing/owl:Nothing allowed)\n- F2: F1 + SubObjectPropertyOf, ObjectPropertyChain, TransitiveObjectProperty\n- F3: F1 + ObjectUnionOf, ObjectComplementOf, ObjectAllValuesFrom, ObjectPropertyRange\n- F4: F3 + SubObjectPropertyOf, EquivalentObjectProperties, InverseObjectProperties, ObjectInverseOf, SymmetricObjectProperty (no transitivity or chains; x1 adds them)\n- F5: F4 + ClassAssertion, ObjectPropertyAssertion, ObjectOneOf, ObjectHasValue\n- x1, x2 are extra variants (F4 + transitive + chains; F3 + DisjointUnion). Fragments are not nested (F2 has no ObjectUnionOf; F4 has no transitivity).\n")
w("| fragment | "+" | ".join(g for g,_ in groups)+" |\n|---|"+"---|"*len(groups))
for name,F in FR:
    w(f"| {name} | "+" | ".join(f"{sum(inside(r,F) for r in rs)} / {len(rs)}" for _,rs in groups)+" |")
w("\nSum-check: p2-accepted is the v1.6.0 EL/ALC recogniser verdict on the normalised clause stream, so F1 and F3 inputs should mostly be accepted; the rows above show how close source syntax tracks it.\n")
# by route
w("### Per production route (unforced_route)\n")
routes=sorted({r['route'] for r in rows},key=lambda k:-sum(r['route']==k for r in rows))
w("| route | inputs | p2-accepted | "+" | ".join(n.split()[0] for n,_ in FR)+" |\n|---|---|---|"+"---|"*len(FR))
for rt in routes:
    rs=[r for r in rows if r['route']==rt]
    w(f"| {rt} | {len(rs)} | {sum(r['p2']=='accepted' for r in rs)} | "+" | ".join(str(sum(inside(r,F) for r in rs)) for _,F in FR)+" |")
# p2-accepted not in F3 etc
acc=[r for r in rows if r['p2']=='accepted']
w("\n### Cross-check with p2\n")
c=collections.Counter()
for r in rows: c[(r['p2']=='accepted', inside(r,F3))]+=1
w("| p2-accepted | inside F3 | inputs |\n|---|---|---|"); [w(f"| {a} | {b} | {v} |") for (a,b),v in sorted(c.items())]
blk=collections.Counter()
for r in acc:
    if not inside(r,F3):
        for h in used(r)-F3: blk[h]+=1
        if topuse(r): blk['<topObjectProperty>']+=1
        if r['kw'].get('header_import',0): blk['Import']+=1
w("\nHeads outside F3 in p2-accepted inputs (the normaliser removes or rewrites these before the recogniser): "+", ".join(f"{h} {c}" for h,c in blk.most_common())+"\n")
# near-miss
w("## 3. Blockers: what keeps inputs out of each fragment\n")
w("For inputs outside the fragment, number of inputs containing each blocking head (an input can have several). Top 10.\n")
for name,F in FR[:5]:
    for gn,rs in groups:
        b=collections.Counter(); sole=collections.Counter()
        for r in rs:
            if inside(r,F): continue
            bl=used(r)-F
            if topuse(r): bl|={'owl:top/bottomObjectProperty'}
            if r['kw'].get('header_import',0): bl|={'Import'}
            for h in bl: b[h]+=1
            if len(bl)==1: sole[next(iter(bl))]+=1
        w(f"- {name}, {gn}: "+"; ".join(f"{h} {v} (sole blocker {sole[h]})" for h,v in b.most_common(10)))
w("")
# 4 axiom type totals
def tab(rs,title,keys):
    w(f"### {title}\n")
    w("| head | inputs using it | total occurrences |\n|---|---|---|")
    for k in keys:
        ni=sum(1 for r in rs if r['heads'].get(k,0)>0); tot=sum(r['heads'].get(k,0) for r in rs)
        if ni: w(f"| {k} | {ni} | {tot} |")
    w("")
allheads=collections.Counter()
for r in rows:
    for h,c in r['heads'].items(): allheads[h]+=c
keys=[k for k,_ in allheads.most_common()]
w("## 4. Axiom and constructor counts per head\n")
w("Counts are occurrences of `Head(` outside string literals. Declaration kinds appear as the wrapper heads Class, ObjectProperty, DataProperty, NamedIndividual, AnnotationProperty, Datatype. Cardinalities: Object/Data Min/Max/Exact Cardinality. Per-input values are in per_input.tsv.\n")
for gn,rs in groups: tab(rs,f"Heads, {gn} ({len(rs)} inputs)",keys)
# 5 IRI
w("## 5. Prefixes and IRI spelling\n")
def iri_kind(r):
    f=r['full_tokens']>0; p=r['pref_tokens']>0
    return 'both' if f and p else 'full only' if f else 'prefixed only' if p else 'none'
w("Entity tokens exclude owl/rdf/rdfs/xsd vocabulary. 'mixed same-IRI' = a prefixed name expands to an IRI that also occurs as a full `<...>` IRI in the same document (the case builtin_aliases canonicalises).\n")
w("| group | none | prefixed only | full only | both forms | mixed same-IRI | no Prefix decl | >=1 Prefix | capped |\n|---|---|---|---|---|---|---|---|---|")
for gn,rs in groups:
    k=collections.Counter(iri_kind(r) for r in rs)
    w(f"| {gn} | {k['none']} | {k['prefixed only']} | {k['full only']} | {k['both']} | {sum(r['mixed_entities']>0 for r in rs)} | {sum(r['prefixes']==0 for r in rs)} | {sum(r['prefixes']>0 for r in rs)} | {sum(r['capped'] for r in rs)} |")
w("\nPrefix declarations per input: median "+str(sorted(r['prefixes'] for r in rows)[n//2])+", max "+str(max(r['prefixes'] for r in rows))+".\n")
w("### Builtin vocabulary use\n")
w("| token | inputs (all) | inputs (p2-accepted) |\n|---|---|---|")
for k in ["owl:Thing","owl:Nothing","topObjectProperty","bottomObjectProperty","topDataProperty","bottomDataProperty"]:
    w(f"| {k} | {sum(r['kw'].get(k,0)>0 for r in rows)} | {sum(r['kw'].get(k,0)>0 for r in acc)} |")
w(f"| Import | {sum(r['kw'].get('header_import',0)>0 for r in rows)} | {sum(r['kw'].get('header_import',0)>0 for r in acc)} |")
w("\n(`owl:Thing` counts only the prefixed spelling; full-IRI spellings of Thing/Nothing are not separately tallied.)\n")
open(D+"REPORT_tables.md","w").write("\n".join(out))
# per-input tsv
with open(D+"per_input.tsv","w") as f:
    cols=sorted(allheads)
    f.write("\t".join(["input","size","p2_status","route","prefixes","full_tokens","pref_tokens","mixed_entities"]+["kw_"+k for k in ["owl:Thing","owl:Nothing","topObjectProperty","bottomObjectProperty","topDataProperty","bottomDataProperty","header_import"]]+cols)+"\n")
    for r in rows:
        f.write("\t".join(map(str,[r['input'],r['size'],r['p2'],r['route'],r['prefixes'],r['full_tokens'],r['pref_tokens'],r['mixed_entities']]+[r['kw'].get(k,0) for k in ["owl:Thing","owl:Nothing","topObjectProperty","bottomObjectProperty","topDataProperty","bottomDataProperty","header_import"]]+[r['heads'].get(c,0) for c in cols]))+"\n")
print("ok",n)
