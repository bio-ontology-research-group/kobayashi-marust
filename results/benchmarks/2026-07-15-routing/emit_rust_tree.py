#!/usr/bin/env python3
"""Translate router-tree.json into the dependency-free Rust decision function."""

import argparse
import json


ROUTE_VARIANTS = {
    "default": "Default",
    "default8": "Default8",
    "default1": "Default1",
    "production_all": "ProductionAll",
    "production_all8": "ProductionAll8",
    "production_all1": "ProductionAll1",
    "cb_plain16": "CbPlain16",
    "cb_plain8": "CbPlain8",
    "cb_plain1": "CbPlain1",
    "cb_absorb16": "CbAbsorb16",
    "cb_absorb8": "CbAbsorb8",
    "cb_absorb1": "CbAbsorb1",
    "cb_trigger16": "CbTrigger16",
    "cb_trigger8": "CbTrigger8",
    "cb_trigger1": "CbTrigger1",
    "cb_absorb_portfolio16": "CbAbsorbPortfolio16",
    "elc": "Elc",
    "elc_cert": "ElcCert",
    "lean": "Lean",
    "ht_general": "HtGeneral",
    "ht_qo": "HtQo",
    "ht_shoq": "HtShoq",
    "ht_card": "HtCard",
    "ht_bridge": "HtBridge",
    "ht_features": "HtFeatures",
    "ht_full": "HtFull",
    "ht_rules": "HtRules",
    "tableau": "Tableau",
    "tab_race": "TabRace",
    "card_fn": "CardFn",
    "nominals": "Nominals",
    "seq_on": "SeqOn",
    "seq_off": "SeqOff",
}


DERIVED = {
    "derived.tbox_fraction": "ratio(s.tbox_axioms, s.logical_axioms)",
    "derived.rbox_fraction": "ratio(s.rbox_axioms, s.logical_axioms)",
    "derived.abox_fraction": "ratio(s.abox_axioms, s.logical_axioms)",
    "derived.rule_fraction": "ratio(s.rule_axioms, s.logical_axioms)",
    "derived.logical_fraction": "ratio(s.logical_axioms, s.ontology_children)",
    "derived.expressions_per_axiom": "ratio(s.concept_expressions, s.logical_axioms)",
    "derived.entities_per_axiom": (
        "ratio(s.distinct_classes + s.distinct_object_properties + "
        "s.distinct_data_properties + s.distinct_individuals, s.logical_axioms)"
    ),
    "derived.existential_fraction": "ratio(s.existentials, s.concept_expressions)",
    "derived.universal_fraction": "ratio(s.universals, s.concept_expressions)",
    "derived.disjunction_fraction": (
        "ratio(s.unions + s.complements, s.concept_expressions)"
    ),
    "derived.cardinality_fraction": (
        "ratio(s.min_cardinalities + s.max_cardinalities + "
        "s.exact_cardinalities, s.concept_expressions)"
    ),
    "derived.role_chain_fraction": "ratio(s.role_chain_axioms, s.logical_axioms)",
}


def rust_string(value):
    return json.dumps(value, ensure_ascii=True)


def expression(feature):
    if feature.startswith("source."):
        return f"s.{feature.split('.', 1)[1]} as f64"
    if feature.startswith("expressivity_code."):
        code = feature.split(".", 1)[1]
        return f"(if e.code == {rust_string(code)} {{ 1.0 }} else {{ 0.0 }})"
    if feature.startswith("expressivity."):
        field = feature.split(".", 1)[1]
        return f"(if e.{field} {{ 1.0 }} else {{ 0.0 }})"
    if feature.startswith("axiom_type."):
        name = feature.split(".", 1)[1]
        return (
            f"s.axiom_types.get({rust_string(name)}).copied().unwrap_or(0) as f64"
        )
    if feature in DERIVED:
        return DERIVED[feature]
    raise ValueError(f"unsupported feature {feature}")


def emit_node(node, indent, output):
    prefix = "    " * indent
    if node["kind"] == "leaf":
        output.append(f"{prefix}Route::{ROUTE_VARIANTS[node['arm']]}")
        return
    output.append(
        f"{prefix}if {expression(node['feature'])} <= {node['threshold']:.17g}_f64 {{"
    )
    emit_node(node["left"], indent + 1, output)
    output.append(f"{prefix}}} else {{")
    emit_node(node["right"], indent + 1, output)
    output.append(f"{prefix}}}")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("tree")
    parser.add_argument("--output", required=True)
    args = parser.parse_args()
    document = json.load(open(args.tree, encoding="utf-8"))
    lines = [
        "// AUTO-GENERATED by results/benchmarks/2026-07-15-routing/emit_rust_tree.py.",
        "// Source features only; no ontology identity enters this function.",
        "use super::Route;",
        "use crate::frontend::profile::OntologyProfile;",
        "",
        "#[inline]",
        "fn ratio(numerator: u64, denominator: u64) -> f64 {",
        "    if denominator == 0 { 0.0 } else { numerator as f64 / denominator as f64 }",
        "}",
        "",
        "pub(super) fn select(profile: &OntologyProfile) -> Route {",
        "    let s = &profile.source;",
        "    let e = &profile.expressivity;",
    ]
    emit_node(document["tree"], 1, lines)
    lines.append("}")
    with open(args.output, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
