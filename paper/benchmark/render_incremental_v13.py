#!/usr/bin/env python3
"""Verify and render the exact-v1.3 incremental scale-check evidence."""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
import statistics


ROOT = Path(__file__).resolve().parents[1]
EVIDENCE = ROOT / "benchmark" / "generated" / "incremental-v13"
OUTPUT = ROOT / "generated" / "incremental-results.tex"
EXPECTED = {
    "results.json": "b656da15b95fec0da54e88809a4777bb7e242d474051f871d980ec85ba894d15",
    "receipt.tsv": "61402c70b42a764cd4daf3ed5fac6adad2d9f29b00f55018bfc986b7da3b1a5e",
    "job.log": "1946564966facc3935e6a27b1b8dbc8815d7f826dd38f909be3545b90783e532",
}
EXPECTED_BINARY = "cb9eabac9f5e4f351947b69f5f61df85cdf450da7f4f398b17cf34b79620aa7d"
EXPECTED_RUNNER = "8086d06639bd16dcde6fb9d806aabf6e4825612e21d3f60b5fbb1628f2492c3d"


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main() -> None:
    for name, expected in EXPECTED.items():
        actual = sha256(EVIDENCE / name)
        if actual != expected:
            raise SystemExit(f"incremental evidence hash mismatch for {name}: {actual}")
    payload = json.loads((EVIDENCE / "results.json").read_text())
    if payload["binary_sha256"] != EXPECTED_BINARY or payload["runner_sha256"] != EXPECTED_RUNNER:
        raise SystemExit("incremental artifact identity mismatch")
    if payload["warmups"] != 1 or payload["repetitions"] != 10:
        raise SystemExit("incremental repetition contract mismatch")

    receipt = dict(line.split("\t", 1) for line in
                   (EVIDENCE / "receipt.tsv").read_text().splitlines())
    if (receipt.get("job_id") != "51036603" or receipt.get("complete") != "true"
            or receipt.get("binary_sha256") != EXPECTED_BINARY
            or receipt.get("runner_sha256") != EXPECTED_RUNNER
            or receipt.get("result_sha256") != EXPECTED["results.json"]):
        raise SystemExit("incremental receipt mismatch")
    log = (EVIDENCE / "job.log").read_text()
    if "INCREMENTAL_V13_OK" not in log or "INCREMENTAL_V13_JOB_OK\t51036603" not in log:
        raise SystemExit("incremental terminal sentinel missing")

    labels = {"el": "EL completion", "cb": "Consequence-based"}
    initial_clauses = {"el": 10_000, "cb": 1_001}
    strategies = {"el": "el_delta", "cb": "cb_delta"}
    lines = [
        "% Generated by paper/benchmark/render_incremental_v13.py. Do not edit.",
        r"\begin{tabular}{lrrrrrrrr}",
        r"\toprule",
        r"Backend & Initial & Reused & New & Add ms & Fresh ms & Ratio & Session MiB & Fresh MiB \\",
        r"\midrule",
    ]
    for case in ("el", "cb"):
        block = payload["cases"][case]
        rows = block["measured_rows"]
        if len(rows) != 10:
            raise SystemExit(f"wrong measured row count for {case}")
        if any(row["strategy"] != strategies[case] or not row["reused_fixpoint"] for row in rows):
            raise SystemExit(f"non-reuse row in {case}")
        if len({row["semantic_result_sha256"] for row in rows}) != 1:
            raise SystemExit(f"semantic result changed across {case} repetitions")
        medians = {
            key: statistics.median(row[key] for row in rows)
            for key in ("incremental_add_s", "fresh_union_s",
                        "incremental_process_peak_kib", "fresh_process_peak_kib")
        }
        for key, value in medians.items():
            if abs(value - block["medians"][key]) > 1e-12:
                raise SystemExit(f"stored median mismatch for {case}:{key}")
        reused = {row["reused_subsumptions"] for row in rows}
        new = {row["new_subsumptions"] for row in rows}
        if len(reused) != 1 or len(new) != 1:
            raise SystemExit(f"unstable reuse counts for {case}")
        ratio = medians["fresh_union_s"] / medians["incremental_add_s"]
        if abs(ratio - block["fresh_over_incremental_add_ratio"]) > 1e-12:
            raise SystemExit(f"stored ratio mismatch for {case}")
        lines.append(
            f"{labels[case]} & {initial_clauses[case]:,} & {next(iter(reused)):,} & "
            f"{next(iter(new)):,} & {medians['incremental_add_s'] * 1000:.2f} & "
            f"{medians['fresh_union_s'] * 1000:.2f} & {ratio:.2f}$\\times$ & "
            f"{medians['incremental_process_peak_kib'] / 1024:.2f} & "
            f"{medians['fresh_process_peak_kib'] / 1024:.2f} \\\\"
        )
    lines.extend([r"\bottomrule", r"\end{tabular}"])
    OUTPUT.write_text("\n".join(lines) + "\n")
    print("INCREMENTAL_V13_EVIDENCE_OK\t2\t20")


if __name__ == "__main__":
    main()
