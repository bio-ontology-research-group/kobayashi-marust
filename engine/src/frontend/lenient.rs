//! Lenient input mode (`--lenient`, `KM_LENIENT=1`, and the `lenient` session
//! option of `km incremental-source`).
//!
//! Rewrites OWL 2 Functional Syntax inputs that OWL API 4.5.29 and HermiT
//! 1.4.3.456 accept in Protégé into valid OWL 2 DL Functional Syntax before the
//! certified reasoning pipeline runs (see `docs/V1.7.0-LENIENT-INPUT.md`).

use std::borrow::Cow;
use std::cell::RefCell;
use std::collections::{BTreeMap, BTreeSet};

use super::sexpr;

/// Prefix of Skolemized anonymous-individual IRIs.
pub const SKOLEM_ANON_PREFIX: &str = "urn:km:lenient:anon";
/// Prefix of the local fragment of Skolemized anonymous-individual IRIs.
pub const SKOLEM_ANON_SHORT_PREFIX: &str = "km_lenient_anon_";
/// Marker substring used when escaping non-RFC3987 characters inside `<...>`.
const IRI_ESCAPE_MARKER: &str = "__km_lenient_";

thread_local! {
    static PUBLISHED_NOTES: RefCell<Vec<String>> = const { RefCell::new(Vec::new()) };
}

/// Whether lenient input mode is active (`--lenient` or `KM_LENIENT=1`).
pub fn enabled() -> bool {
    std::env::var_os("KM_LENIENT").is_some_and(|v| !v.is_empty() && v != "0" && v != "false")
}

/// Clear the published lenient-rewrite notes for the current thread.
pub fn clear_published_notes() {
    PUBLISHED_NOTES.with(|notes| notes.borrow_mut().clear());
}

/// Replace the published lenient-rewrite notes for the current thread.
pub fn set_published_notes(new_notes: Vec<String>) {
    PUBLISHED_NOTES.with(|notes| *notes.borrow_mut() = new_notes);
}

/// Record lenient-rewrite notes for the current thread without duplicates.
pub fn record_published_notes(new_notes: Vec<String>) {
    if new_notes.is_empty() {
        return;
    }
    PUBLISHED_NOTES.with(|notes| {
        let mut current = notes.borrow_mut();
        for note in new_notes {
            if !current.contains(&note) {
                current.push(note);
            }
        }
    });
}

/// Return the published lenient-rewrite notes for the current thread.
pub fn published_notes() -> Vec<String> {
    PUBLISHED_NOTES.with(|notes| notes.borrow().clone())
}

/// Whether `token` (with or without `<...>`) is a Skolemized anonymous
/// individual generated by lenient mode.
pub fn is_skolem_anon_iri(token: &str) -> bool {
    let inner = token
        .trim()
        .strip_prefix('<')
        .and_then(|s| s.strip_suffix('>'))
        .unwrap_or(token);
    inner.starts_with(SKOLEM_ANON_PREFIX)
}

/// Whether an `IriRegistry` short name belongs to a Skolemized anonymous
/// individual generated by lenient mode.
pub fn is_skolem_anon_short(name: &str) -> bool {
    name.starts_with(SKOLEM_ANON_SHORT_PREFIX)
}

/// Whether `s` contains any `__km_lenient_` escaped IRI characters.
pub fn has_escaped_iri(s: &str) -> bool {
    s.contains(IRI_ESCAPE_MARKER)
}

/// Restore any `__km_lenient_uXXXX__` or `__km_lenient_UXXXXXXXX__` escape
/// sequences in `s` back to their original characters.
pub fn unescape_iri(s: &str) -> Cow<'_, str> {
    if !s.contains(IRI_ESCAPE_MARKER) {
        return Cow::Borrowed(s);
    }
    let mut out = String::with_capacity(s.len());
    let mut rest = s;
    while let Some(pos) = rest.find(IRI_ESCAPE_MARKER) {
        out.push_str(&rest[..pos]);
        let after = &rest[pos + IRI_ESCAPE_MARKER.len()..];
        if let Some(hex_and_tail) = after.strip_prefix('u') {
            if hex_and_tail.len() >= 6 && hex_and_tail.as_bytes()[4..6] == *b"__" {
                if let Ok(code) = u32::from_str_radix(&hex_and_tail[..4], 16) {
                    if let Some(ch) = char::from_u32(code) {
                        out.push(ch);
                        rest = &hex_and_tail[6..];
                        continue;
                    }
                }
            }
        } else if let Some(hex_and_tail) = after.strip_prefix('U') {
            if hex_and_tail.len() >= 10 && hex_and_tail.as_bytes()[8..10] == *b"__" {
                if let Ok(code) = u32::from_str_radix(&hex_and_tail[..8], 16) {
                    if let Some(ch) = char::from_u32(code) {
                        out.push(ch);
                        rest = &hex_and_tail[10..];
                        continue;
                    }
                }
            }
        }
        out.push_str(IRI_ESCAPE_MARKER);
        rest = after;
    }
    out.push_str(rest);
    Cow::Owned(out)
}

fn is_rfc3987_ucschar(c: char) -> bool {
    let u = c as u32;
    matches!(
        u,
        0xA0..=0xD7FF
            | 0xF900..=0xFDCF
            | 0xFDF0..=0xFFEF
            | 0x10000..=0x1FFFD
            | 0x20000..=0x2FFFD
            | 0x30000..=0x3FFFD
            | 0x40000..=0x4FFFD
            | 0x50000..=0x5FFFD
            | 0x60000..=0x6FFFD
            | 0x70000..=0x7FFFD
            | 0x80000..=0x8FFFD
            | 0x90000..=0x9FFFD
            | 0xA0000..=0xAFFFD
            | 0xB0000..=0xBFFFD
            | 0xC0000..=0xCFFFD
            | 0xD0000..=0xDFFFD
            | 0xE1000..=0xEFFFD
    )
}

/// Escape non-RFC3987 characters in a `<...>` FullIRI token so that the
/// resulting token satisfies `km_owl_functional_syntax::full_iri_valid`.
fn escape_full_iri(token: &str) -> Option<String> {
    let body = token.strip_prefix('<')?.strip_suffix('>')?;
    if body.is_empty() || body.contains(['\n', '\r']) {
        return None;
    }
    let mut escaped = String::with_capacity(body.len() + 32);
    let mut seen_hash = false;
    let bytes = body.as_bytes();
    let mut i = 0usize;
    while i < body.len() {
        let ch = body[i..].chars().next()?;
        let len = ch.len_utf8();
        let safe = if ch.is_ascii() {
            let b = ch as u8;
            if b.is_ascii_alphanumeric()
                || matches!(
                    b,
                    b'-' | b'.'
                        | b'_'
                        | b'~'
                        | b'/'
                        | b':'
                        | b'@'
                        | b'!'
                        | b'$'
                        | b'&'
                        | b'\''
                        | b'('
                        | b')'
                        | b'*'
                        | b'+'
                        | b';'
                        | b'='
                        | b','
                )
            {
                true
            } else if b == b'?' {
                !seen_hash
            } else if b == b'#' && !seen_hash {
                seen_hash = true;
                true
            } else if b == b'%' {
                i + 2 < bytes.len()
                    && bytes[i + 1].is_ascii_hexdigit()
                    && bytes[i + 2].is_ascii_hexdigit()
            } else {
                false
            }
        } else {
            is_rfc3987_ucschar(ch)
        };
        if safe {
            escaped.push(ch);
        } else {
            let code = ch as u32;
            if code <= 0xFFFF {
                escaped.push_str(&format!("{IRI_ESCAPE_MARKER}u{code:04x}__"));
            } else {
                escaped.push_str(&format!("{IRI_ESCAPE_MARKER}U{code:08x}__"));
            }
        }
        i += len;
    }
    let full = format!("<{escaped}>");
    km_owl_functional_syntax::full_iri_valid(&full).then_some(full)
}

fn sanitize_anon_id(raw: &str) -> String {
    let id = raw.strip_prefix("_:").unwrap_or(raw);
    let mut out = String::with_capacity(id.len());
    for b in id.bytes() {
        if b.is_ascii_alphanumeric() || matches!(b, b'_' | b'-' | b'.') {
            out.push(b as char);
        } else {
            out.push_str(&format!("_x{b:02x}_"));
        }
    }
    out
}

fn fresh_skolem_anon_namespace(text: &str) -> String {
    let mut candidate = SKOLEM_ANON_PREFIX.to_string();
    let mut nonce = 1u64;
    while text.contains(&candidate) {
        candidate = format!("{SKOLEM_ANON_PREFIX}{nonce}");
        nonce += 1;
    }
    candidate
}

fn ontology_close_offset(text: &str) -> Option<usize> {
    let mut depth = 0usize;
    let mut previous: Option<&str> = None;
    let mut inside = false;
    for token in sexpr::tokens(text) {
        match token {
            "(" => {
                if depth == 0 && previous == Some("Ontology") {
                    inside = true;
                }
                depth += 1;
            }
            ")" => {
                depth = depth.checked_sub(1)?;
                if depth == 0 && inside {
                    return Some(token.as_ptr() as usize - text.as_ptr() as usize);
                }
            }
            _ => {}
        }
        previous = Some(token);
    }
    None
}

fn count_lenient_datatypes(
    text: &str,
    prefixes: &BTreeMap<String, String>,
) -> (usize, usize) {
    let mut rdfs_literal = 0usize;
    let mut unknown_literal = 0usize;
    let mut stream = sexpr::tokens(text).peekable();
    while let Some(literal) = stream.next() {
        if !literal.starts_with('"') {
            continue;
        }
        let Some(suffix) = stream.peek().copied() else {
            continue;
        };
        if suffix.starts_with('@') {
            stream.next();
            continue;
        }
        let Some(datatype) = suffix.strip_prefix("^^") else {
            continue;
        };
        stream.next();
        let datatype = if datatype.is_empty() {
            stream.next().unwrap_or("")
        } else {
            datatype
        };
        let expanded = super::conformance::expand(datatype, prefixes);
        if expanded == "http://www.w3.org/2000/01/rdf-schema#Literal" {
            rdfs_literal += 1;
        } else if !super::conformance::datatypes::builtin(&expanded)
            && expanded != "http://www.w3.org/2002/07/owl#real"
        {
            unknown_literal += 1;
        }
    }
    let unknown_ranges = super::conformance::datatypes::count_unknown_data_ranges(text, prefixes);
    (rdfs_literal, unknown_literal + unknown_ranges)
}

/// Rewrite `text` under lenient mode into valid OWL 2 DL Functional Syntax,
/// returning `(rewritten_text, lenient_notes)`. When lenient mode is off or no
/// rewrite applies, returns `Cow::Borrowed(text)`.
pub fn rewrite_source(text: &str) -> Result<(Cow<'_, str>, Vec<String>), String> {
    if !enabled() {
        return Ok((Cow::Borrowed(text), Vec::new()));
    }
    let mut notes = Vec::new();
    let mut working: Cow<'_, str> = Cow::Borrowed(text);

    // 1. Escape non-RFC3987 characters in `<...>` FullIRIs and unescape `\~`
    // in `xsd:pattern` facet literals.
    {
        let src: &str = &working;
        let mut valid_iris: crate::fxhash::FxHashSet<&str> = crate::fxhash::FxHashSet::default();
        let mut invalid_iris: crate::fxhash::FxHashMap<&str, Option<String>> =
            crate::fxhash::FxHashMap::default();
        let mut edits: Vec<(usize, usize, String)> = Vec::new();
        let mut iri_count = 0usize;
        let mut pattern_count = 0usize;
        let mut prev_tok = "";
        for tok in sexpr::tokens(src) {
            if tok.starts_with('<') && tok.ends_with('>') && tok.len() >= 2 {
                if !valid_iris.contains(tok) {
                    if let Some(cached) = invalid_iris.get(tok) {
                        if let Some(escaped) = cached {
                            let start = tok.as_ptr() as usize - src.as_ptr() as usize;
                            edits.push((start, start + tok.len(), escaped.clone()));
                            iri_count += 1;
                        }
                    } else if km_owl_functional_syntax::full_iri_valid(tok) {
                        valid_iris.insert(tok);
                    } else {
                        let escaped = escape_full_iri(tok);
                        if let Some(ref repl) = escaped {
                            let start = tok.as_ptr() as usize - src.as_ptr() as usize;
                            edits.push((start, start + tok.len(), repl.clone()));
                            iri_count += 1;
                        }
                        invalid_iris.insert(tok, escaped);
                    }
                }
            } else if tok.starts_with('"')
                && tok.ends_with('"')
                && tok.contains(r"\\~")
                && (prev_tok == "xsd:pattern"
                    || prev_tok.ends_with("#pattern>")
                    || prev_tok.ends_with(":pattern"))
            {
                let start = tok.as_ptr() as usize - src.as_ptr() as usize;
                edits.push((start, start + tok.len(), tok.replace(r"\\~", "~")));
                pattern_count += 1;
            }
            prev_tok = tok;
        }
        if !edits.is_empty() {
            let mut out = String::with_capacity(src.len() + 32 * edits.len());
            let mut copied = 0usize;
            for (start, end, repl) in edits {
                out.push_str(&src[copied..start]);
                out.push_str(&repl);
                copied = end;
            }
            out.push_str(&src[copied..]);
            working = Cow::Owned(out);
            if iri_count > 0 {
                notes.push(format!(
                    "escaped non-RFC3987 character(s) in {iri_count} IRI occurrence(s)"
                ));
            }
            if pattern_count > 0 {
                notes.push(format!(
                    "unescaped \\~ in {pattern_count} xsd:pattern literal(s)"
                ));
            }
        }
    }

    let Ok(prefixes) = super::conformance::prefixes(&working) else {
        return Ok((working, notes));
    };

    // 2. Record `rdfs:Literal`-typed literals and unknown datatypes accepted
    // under lenient mode (`conformance::unknown_datatypes_free` is enabled).
    let (rdfs_literal_count, unknown_dt_count) = count_lenient_datatypes(&working, &prefixes);
    if rdfs_literal_count > 0 {
        notes.push(format!(
            "accepted {rdfs_literal_count} literal(s) typed rdfs:Literal as opaque data value(s)"
        ));
    }
    if unknown_dt_count > 0 {
        notes.push(format!(
            "accepted {unknown_dt_count} unknown datatype occurrence(s) as free"
        ));
    }

    let mut extra_declarations: Vec<String> = Vec::new();

    // 3. Skolemize anonymous individuals when `ObjectHasValue`, `ObjectOneOf`,
    // or Section 11.2 forest restrictions are violated.
    if working.contains("_:") {
        if let Some(anon_note) =
            super::conformance::anonymous::skolemizable_violation(&working, &prefixes)
        {
            let src: &str = &working;
            let ns = fresh_skolem_anon_namespace(src);
            let mut edits: Vec<(usize, usize, String)> = Vec::new();
            let mut declared_skolems: BTreeSet<String> = BTreeSet::new();
            for tok in sexpr::tokens(src) {
                if tok.starts_with("_:") {
                    let sanitized = sanitize_anon_id(tok);
                    let iri = format!("<{ns}#{SKOLEM_ANON_SHORT_PREFIX}{sanitized}>");
                    let start = tok.as_ptr() as usize - src.as_ptr() as usize;
                    declared_skolems.insert(iri.clone());
                    edits.push((start, start + tok.len(), iri));
                }
            }
            if !edits.is_empty() {
                let mut out = String::with_capacity(src.len() + 32 * edits.len());
                let mut copied = 0usize;
                for (start, end, repl) in edits {
                    out.push_str(&src[copied..start]);
                    out.push_str(&repl);
                    copied = end;
                }
                out.push_str(&src[copied..]);
                working = Cow::Owned(out);
                for iri in declared_skolems {
                    extra_declarations.push(format!("Declaration(NamedIndividual({iri}))"));
                }
                notes.push(anon_note);
            }
        }
    }

    // 4. Inject missing entity declarations (`AnnotationProperty`, etc.).
    if let Ok(missing) = super::conformance::entities::missing_declarations(&working, &prefixes) {
        if !missing.is_empty() {
            let mut counts: BTreeMap<&'static str, usize> = BTreeMap::new();
            for (kind, iri) in missing {
                *counts.entry(kind).or_default() += 1;
                extra_declarations.push(format!("Declaration({kind}(<{iri}>))"));
            }
            for (kind, count) in counts {
                notes.push(format!("declared {count} undeclared {kind} entity/entities"));
            }
        }
    }

    // 5. Append generated `Declaration(...)` axioms before the closing `)` of `Ontology(...)`.
    if !extra_declarations.is_empty() {
        if let Some(close) = ontology_close_offset(&working) {
            let src: &str = &working;
            let mut out =
                String::with_capacity(src.len() + extra_declarations.len() * 64 + 4);
            out.push_str(&src[..close]);
            out.push('\n');
            for decl in extra_declarations {
                out.push_str(&decl);
                out.push('\n');
            }
            out.push_str(&src[close..]);
            working = Cow::Owned(out);
        }
    }

    Ok((working, notes))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn unescape_iri_roundtrips_non_ascii_and_brackets() {
        for raw in [
            "<http://puls.cs.helsinki.fi/med/expression1#en-Baden-W\u{FFFD}rttemberg-N>",
            "<http://www.ontologydesignpatterns.org/cp/owl/situation.owl#[event:Event,]>",
        ] {
            assert!(!km_owl_functional_syntax::full_iri_valid(raw));
            let escaped = escape_full_iri(raw).expect("escaped");
            assert!(km_owl_functional_syntax::full_iri_valid(&escaped));
            let inner = &escaped[1..escaped.len() - 1];
            assert_eq!(
                format!("<{}>", unescape_iri(inner)),
                raw
            );
        }
    }

    #[test]
    fn lenient_rewrite_handles_all_corpus_invalid_classes() {
        let _env = crate::test_env::write();
        let _lenient = crate::test_env::EnvVar::set("KM_LENIENT", "1");
        let source = "Prefix(:=<http://example.org/t#>)\n\
            Prefix(rdfs:=<http://www.w3.org/2000/01/rdf-schema#>)\n\
            Prefix(xsd:=<http://www.w3.org/2001/XMLSchema#>)\n\
            Ontology(\n\
              Declaration(Class(:A))\n\
              Declaration(Class(<http://example.org/t#B\u{FFFD}[1]>))\n\
              Declaration(ObjectProperty(:r))\n\
              Declaration(DataProperty(:dp))\n\
              AnnotationAssertion(:undeclaredAnnot :A \"label\")\n\
              SubClassOf(:A ObjectHasValue(:r _:b1))\n\
              SubClassOf(:A DataHasValue(:dp \"NULL\"^^rdfs:Literal))\n\
              SubClassOf(:A DataSomeValuesFrom(:dp DatatypeRestriction(xsd:string xsd:pattern \"[\\\\~]a\")))\n\
              ClassAssertion(<http://example.org/t#B\u{FFFD}[1]> _:b1)\n\
            )";
        let (rewritten, notes) = rewrite_source(source).expect("rewritten");
        crate::frontend::conformance::check_user_source(&rewritten).expect("valid OWL 2 DL");
        assert!(notes.iter().any(|n| n.contains("IRI")));
        assert!(notes.iter().any(|n| n.contains("xsd:pattern")));
        assert!(notes.iter().any(|n| n.contains("rdfs:Literal")));
        assert!(notes.iter().any(|n| n.contains("ObjectHasValue")));
        assert!(notes.iter().any(|n| n.contains("AnnotationProperty")));
    }
}
